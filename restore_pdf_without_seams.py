# -*- coding: utf-8 -*-
"""Repair seam artifacts in a *previously restored* flat-image PDF.

Designed for the synthetic PDF generated by this project's handler_media.restore_pdf:
one full-page raster image followed by crop overlays on each page.
Does not need or modify the private restore map. Result contains restored content:
keep it private.

Usage:
  python restore_pdf_without_seams.py INPUT_RESTORED.pdf OUTPUT.pdf

Not a generic PDF tool. Refuses unexpected structures rather than silently
reconstructing a page incorrectly. This is a visual repair, not byte-identical
recovery of the source document.
"""
from __future__ import annotations

import argparse
import io
import math
from pathlib import Path

import pymupdf as fitz
from PIL import Image
import numpy as np


def _native_size(rect, scale):
    return (int(round(rect.width * scale)), int(round(rect.height * scale)))


def repair(source: Path, output: Path, scale=2.0, border=3):
    if source.resolve() == output.resolve():
        raise ValueError('Source and output cannot be the same.')
    if output.exists():
        raise FileExistsError(f'Output already exists: {output}')
    with fitz.open(source) as src, fitz.open() as dst:
        if not src.page_count:
            raise ValueError('Source PDF has no pages.')
        for i, page in enumerate(src):
            images = page.get_images(full=True)
            if len(images) < 2:
                raise ValueError(f'Page {i+1}: expected a full-page image and crop overlays.')
            # For the project's restored PDF, each image object occurs once per page.
            layers = []
            for item in images:
                xref = item[0]
                rects = page.get_image_rects(xref)
                if len(rects) != 1:
                    raise ValueError(f'Page {i+1}: ambiguous image placement for xref {xref}.')
                data = src.extract_image(xref)['image']
                layer = Image.open(io.BytesIO(data)).convert('RGB')
                layers.append((rects[0], layer))

            fullbox, whole = layers[0]
            if not (abs(fullbox.x0 - page.rect.x0) < 0.1 and
                    abs(fullbox.y0 - page.rect.y0) < 0.1 and
                    abs(fullbox.width - page.rect.width) < 0.1 and
                    abs(fullbox.height - page.rect.height) < 0.1):
                raise ValueError(f'Page {i+1}: first image does not cover the full page.')

            pixels = _native_size(page.rect, scale)
            canvas = whole.resize(pixels, Image.Resampling.LANCZOS)
            for region, crop in layers[1:]:
                # These restored crop PNGs were captured from the source at 2x.
                # Preserve their native pixel size instead of letting the PDF
                # renderer interpolate them independently at the redaction edge.
                x0 = int(round(region.x0 * scale))
                y0 = int(round(region.y0 * scale))
                rw = int(round(region.width * scale))
                rh = int(round(region.height * scale))
                if abs(crop.width - rw) > 2 or abs(crop.height - rh) > 2:
                    raise ValueError(f'Page {i+1}: crop scale does not match page mapping.')
                if crop.size != (rw, rh):
                    crop = crop.resize((rw, rh), Image.Resampling.BILINEAR)
                # Small edge-color extension masks antialiased black pixels left
                # at the perimeter by the original redaction rasterization.
                arr = np.asarray(crop)
                extended = Image.fromarray(np.pad(arr, ((border,border),(border,border),(0,0)), mode='edge'))
                canvas.paste(extended, (x0-border, y0-border))

            new_page = dst.new_page(width=page.rect.width, height=page.rect.height)
            mem = io.BytesIO()
            canvas.save(mem, format='PNG')
            new_page.insert_image(new_page.rect, stream=mem.getvalue(), keep_proportion=False)
            print(f'Page {i+1}: flattened {len(layers)-1} restored regions')
            for _, layer in layers:
                layer.close()
            canvas.close()
        dst.save(output, garbage=4, deflate=True)
    print('WROTE:', output)


if __name__ == '__main__':
    p = argparse.ArgumentParser(description='Flatten a restored project PDF and repair its visible seam artifacts.')
    p.add_argument('restored_pdf', type=Path)
    p.add_argument('output_pdf', type=Path)
    p.add_argument('--scale', type=float, default=2.0, help='Source crop scale (default 2.0)')
    p.add_argument('--border-px', type=int, default=3, help='Edge-pixel extension (default 3)')
    args = p.parse_args()
    if not math.isfinite(args.scale) or args.scale <= 0 or not 0 <= args.border_px <= 12:
        p.error('Invalid --scale or --border-px')
    repair(args.restored_pdf, args.output_pdf, args.scale, args.border_px)
